#!/usr/bin/env node
/**
 * Reads Flutter ARB files (achievementTitle_* / achievementDescription_*) and emits
 * backend/src/i18n/generated/achievementArbBundles.ts for server-side inbox copy.
 *
 * Run after changing achievement strings in app_*.arb:
 *   node scripts/build_achievement_arb_bundles.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const l10nDir = path.join(root, 'client', 'lib', 'l10n');
const outPath = path.join(root, 'backend', 'src', 'i18n', 'generated', 'achievementArbBundles.ts');

const LANGS = ['en', 'nl', 'de', 'fr', 'es', 'it', 'pl', 'pt'];

function extractBundle(arb) {
  const titles = {};
  const descriptions = {};
  for (const [k, v] of Object.entries(arb)) {
    if (k.startsWith('@')) continue;
    if (typeof v !== 'string') continue;
    if (k.startsWith('achievementTitle_')) {
      const id = k.slice('achievementTitle_'.length);
      titles[id] = v;
    } else if (k.startsWith('achievementDescription_')) {
      const id = k.slice('achievementDescription_'.length);
      descriptions[id] = v;
    }
  }
  const allIds = new Set([...Object.keys(titles), ...Object.keys(descriptions)]);
  const byId = {};
  for (const id of allIds) {
    const row = {};
    if (titles[id] != null) row.title = titles[id];
    if (descriptions[id] != null) row.description = descriptions[id];
    byId[id] = row;
  }
  return byId;
}

const bundles = {};
for (const lang of LANGS) {
  const arbPath = path.join(l10nDir, `app_${lang}.arb`);
  const arb = JSON.parse(fs.readFileSync(arbPath, 'utf8'));
  bundles[lang] = extractBundle(arb);
}

fs.mkdirSync(path.dirname(outPath), { recursive: true });

const banner = `/**
 * Auto-generated by scripts/build_achievement_arb_bundles.mjs — do not edit.
 * Source: client/lib/l10n/app_*.arb (achievementTitle_* / achievementDescription_*).
 */

`;

const body = `export const ACHIEVEMENT_ARB_BY_LANG = ${JSON.stringify(bundles, null, 2)} as const;

export type AchievementArbBundles = typeof ACHIEVEMENT_ARB_BY_LANG;
`;

fs.writeFileSync(outPath, banner + body, 'utf8');
console.log(`build_achievement_arb_bundles: wrote ${path.relative(root, outPath)} (${LANGS.length} locales).`);
